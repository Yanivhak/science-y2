def mend_table(cw=84, ch=74, width=560):
    """8 הטורים העיקריים, שורות 1–4, כמו שמנדלייב יכול היה למלא אותם ב־1869: טור 8 (c8) מופיע רק בצעד האחרון; Ga ו־Ge — משבצות ריקות עם „?”."""
    lw, top = 30, 30
    W, H = lw + 8 * cw + 8, top + 4 * ch + 8
    YEARS = {'Ga': '1875', 'Ge': '1886'}
    g = ''
    for r_ in range(4):
        for c in range(8):
            e = ROWS[r_][c]
            if not e: continue
            sym, Z, nm = e
            x, y, w_, h_ = lw + c * cw + 3, top + r_ * ch + 3, cw - 6, ch - 6
            if sym in YEARS:
                g += (f'<g class="gap"><rect x="{x}" y="{y}" width="{w_}" height="{h_}" rx="9" fill="none" stroke="{GOLD}" stroke-width="2" stroke-dasharray="6 5"/>'
                      f'<g class="q">' + T(x + w_ / 2, y + h_ * .64, '?', round(ch * .42), GOLD, 800) + '</g>'
                      f'<g class="fill"><rect x="{x}" y="{y}" width="{w_}" height="{h_}" rx="9" fill="{GOLD}" fill-opacity=".18" stroke="{GOLD}" stroke-width="2.5"/>'
                      + T(x + w_ / 2, y + h_ * .50, sym, round(ch * .34), '#FFFFFF', 800)
                      + T(x + w_ / 2, y + h_ - 9, YEARS[sym], 14, GOLD, 800) + '</g></g>')
                continue
            cell = (f'<rect x="{x}" y="{y}" width="{w_}" height="{h_}" rx="9" fill="rgba(255,255,255,.11)" stroke="rgba(255,255,255,.45)" stroke-width="1.5"/>'
                    + T(x + w_ / 2, y + h_ * .64, sym, round(ch * .34), '#FFFFFF', 800))
            if sym == 'Ar':   # רק הארגון מקבל שנה: הוא היחיד שהשנה שלו על המסך (1894)
                cell = (f'<rect x="{x}" y="{y}" width="{w_}" height="{h_}" rx="9" fill="{GOLD}" fill-opacity=".18" stroke="{GOLD}" stroke-width="2.5"/>'
                        + T(x + w_ / 2, y + h_ * .50, sym, round(ch * .34), '#FFFFFF', 800)
                        + T(x + w_ / 2, y + h_ - 9, '1894', 14, GOLD, 800))
            g += f'<g class="{"c8" if c == 7 else ""}">{cell}</g>'
    return svg(W, H, g, width)

