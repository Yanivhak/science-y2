def head(eyebrow, title, size='t-md', stop=False, timer=None):
    eyebrow = re.sub(r'^(\d+) · ', r'\1. ', eyebrow).replace(' · ', ', ')   # בלי „·” בטקסט שהתלמידים קוראים
    eb = f'<p class="eyebrow{" stop" if stop else ""} anim">{eyebrow}</p>' if eyebrow else ''
    tt = f'<h2 class="ttl {size} anim">{title}</h2>'
    if timer:
        return f'  <div class="hdr"><div>{eb}{tt}</div><div class="timer anim" data-sec="{timer}"></div></div>'
    return f'  {eb}\n  {tt}'

def qa(items, cls=''):
    rows = ''.join(f'<div class="frag keep"><i>{k}</i><p>{q}</p><span class="ans">{a}</span></div>' for k, q, a in items)
    return f'<div class="qa {cls}">{rows}</div>'

def mcq(opts, ok, cls='four'):
    b = ''.join(f'<button{" data-ok" if i == ok else ""}>{o}</button>' for i, o in enumerate(opts))
    return f'<div class="mcq {cls} anim mt">{b}</div>'


