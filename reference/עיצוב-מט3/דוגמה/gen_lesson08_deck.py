def rep_rows(w=760):
    """המחזוריות בציור: שורות 2 ו־3, צבע אחד לכל טור. השורה השנייה חוזרת על הדפוס של הראשונה (rr3), ואז הטורים נדלקים (rcol)."""
    hues = ['#FF8A8A', '#FFB86B', '#FFE07A', '#B8F07A', '#7AE0C8', '#7AC4FF', '#A99BFF', '#F0A6FF']
    cw, ch, x0, y0 = 88, 74, 10, 10
    g = ''
    for r_, cls in [(1, 'rr2'), (2, 'rr3')]:
        g += f'<g class="{cls}">'
        for c in range(8):
            sym, Z, nm = ROWS[r_][c]
            x, y = x0 + c * cw, y0 + (r_ - 1) * (ch + 14)
            g += (f'<rect x="{x + 3}" y="{y}" width="{cw - 6}" height="{ch}" rx="10" fill="{hues[c]}" fill-opacity=".28" stroke="{hues[c]}" stroke-width="2.5"/>'
                  + T(x + cw / 2, y + ch * .62, sym, 28, '#FFFFFF', 800))
        g += '</g>'
    g += '<g class="rcol">' + ''.join(f'<rect x="{x0 + c * cw}" y="{y0 - 5}" width="{cw}" height="{2 * ch + 24}" rx="14" fill="none" stroke="{hues[c]}" stroke-width="3.5"/>' for c in range(8)) + '</g>'
    return svg(x0 * 2 + 8 * cw, y0 * 2 + 2 * ch + 24, g, w, 'rrep')

